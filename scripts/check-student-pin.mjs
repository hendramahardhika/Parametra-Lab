import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result=await build({stdin:{contents:"export * from './lib/student-pin'; export * from './lib/student-identity';",resolveDir:process.cwd()},bundle:true,write:false,platform:'node',format:'esm'});
const api=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const values=new Map();
globalThis.window={location:{pathname:'/pin-test/index.html'}};
globalThis.localStorage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,String(v)),removeItem:k=>values.delete(k)};
const A={fullName:'Siswa A',className:'XI TP 1',attendance:1};
const B={fullName:'Siswa B',className:'XI TP 1',attendance:2};
const session=api.studentIdentityKey(window.location.pathname);
for(const pin of ['','12345','1234567','abcdef','12 345','１２３４５６']) assert.throws(()=>api.validateStudentPin(pin));
localStorage.setItem(session,JSON.stringify(A));
assert.equal(api.readStudentIdentity(),null,'Old non-PIN session must sign in again');
await api.signInWithStudentPin(A,'058239');
assert.deepEqual(api.readStudentIdentity(),A);
const keyA=session+':pin:'+api.studentAccountId(A),recordA=localStorage.getItem(keyA);
assert.ok(recordA&&!recordA.includes('058239'));
assert.ok(!localStorage.getItem(session).includes('058239'));
localStorage.removeItem(session);
await assert.rejects(()=>api.signInWithStudentPin(A,'111111'),/PIN tidak sesuai/);
assert.equal(api.readStudentIdentity(),null);
assert.equal(localStorage.getItem(keyA),recordA,'Wrong PIN must not replace credentials');
await api.signInWithStudentPin({...A,fullName:'Nama diperbaiki'},'058239');
assert.equal(api.readStudentIdentity().fullName,'Nama diperbaiki');
assert.equal(localStorage.getItem(keyA),recordA,'Name changes retain existing PIN');
await api.signInWithStudentPin(B,'729148');
assert.equal(api.readStudentIdentity().attendance,2);
localStorage.removeItem(session);
await assert.rejects(()=>api.signInWithStudentPin(A,'729148'),/PIN tidak sesuai/);
await api.signInWithStudentPin(A,'058239');
assert.equal(api.readStudentIdentity().attendance,1);
localStorage.removeItem(session);
localStorage.setItem(keyA,'invalid JSON');
await assert.rejects(()=>api.signInWithStudentPin(A,'058239'),/tidak dapat dibaca/);
assert.equal(api.readStudentIdentity(),null);
console.log('PASS: six-digit PIN validation, masked field integration, enrolment, wrong PIN rejection, separate pupil PINs, relogin, name edit, non-plaintext storage, pre-PIN session expiry and corrupt-record rejection. Browser storage mocked; no server authentication claimed.');
